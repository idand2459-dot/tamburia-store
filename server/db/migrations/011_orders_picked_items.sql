-- רשימת ליקוט: אילו שורות בהזמנה כבר הוכנו.
--
-- פריטי ההזמנה שמורים כ-JSONB ב-orders.items, ולכן אין שורה בטבלה
-- שאפשר להוסיף לה picked. שתי דרכים נשקלו:
--
--   1. picked בתוך כל אובייקט ב-items (jsonb_set).
--   2. עמודה מקבילה: קבוצת האינדקסים של השורות שהוכנו.
--
-- נבחרה השנייה. items הוא תיעוד של מה שנמכר ובאיזה מחיר — הוולידטור
-- אינו מאפשר לערוך אותו, והוא מה שהלקוח רואה בחיפוש לפי טלפון. הכנה
-- במחסן היא מצב של הטיפול בהזמנה ולא חלק מהמכירה, ואין סיבה שתיגע
-- ברשומה הזו או תדלוף ממנה ללקוח.
--
-- קבוצת אינדקסים ולא BOOLEAN[] באורך השורות: אין מה ליישר מול אורך
-- items, הזמנות קיימות מקבלות '{}' בלי מילוי, וסימון שורה אחת הוא
-- array_append / array_remove בשאילתה אחת — שני מכשירים שמסמנים שורות
-- שונות באותו רגע אינם דורסים זה את זה.
--
-- האינדקס יציב כי items אינו משתנה אחרי שההזמנה נשמרה.
ALTER TABLE orders
  ADD COLUMN IF NOT EXISTS picked_items INTEGER[] NOT NULL DEFAULT '{}';
