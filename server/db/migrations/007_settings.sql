-- הגדרות של מסך הניהול, שצריכות להיראות זהות בכל מכשיר.
--
-- טבלת מפתח/ערך ולא עמודה לכל הגדרה: אלה העדפות של המשתמש ולא
-- נתונים של הדומיין, הן מעטות, ואין ביניהן קשר שמצדיק סכימה. השרת
-- מכיר רשימה סגורה של מפתחות (server/validators/setting.validator.js)
-- ולכן הטבלה אינה פתוחה לכתיבת מה שבא.
--
-- הערך הוא TEXT ולא JSONB: ההגדרה היחידה כרגע היא חותמת זמן,
-- והוולידטור של כל מפתח הוא זה שיודע איך לפרש את המחרוזת.
CREATE TABLE IF NOT EXISTS settings (
  key        VARCHAR(100) PRIMARY KEY,
  value      TEXT,
  updated_at TIMESTAMP NOT NULL DEFAULT NOW()
);
