-- הסתרת מוצר במקום מחיקתו.
--
-- ההזמנות, הביקורות ומחשבון הצבע מפנים למוצרים לפי id. מחיקת מוצר
-- שאזל מהמדף הייתה מנתקת הזמנה ישנה מהפריט שנמכר בה, ולכן מוצר
-- שאינו בחנות מסומן active = false ונשאר במסד.
--
-- ברירת המחדל true, ו-NOT NULL: כל 408 המוצרים שכבר במסד נשארים
-- גלויים, וההסתרה היא פעולה מפורשת.
ALTER TABLE products
  ADD COLUMN IF NOT EXISTS active BOOLEAN NOT NULL DEFAULT true;

-- כל שליפה של החנות מסננת לפי העמודה הזו, והיא סלקטיבית מאוד לצד
-- אחד (מעט מוסתרים): אינדקס חלקי על המוסתרים בלבד הוא מה שמשרת את
-- מסך הניהול, והחנות ממילא סורקת את הרוב.
CREATE INDEX IF NOT EXISTS products_hidden_idx ON products (id) WHERE NOT active;
