/**
 * גלילה חלקה אל מקטע בעמוד, לפי סלקטור.
 *
 * מקטעי עמוד הבית אינם עמודים נפרדים, ולכן הכפתורים שמובילים אליהם
 * גוללים ולא מנווטים. שלושה מקומות עשו את זה באותן שתי שורות בדיוק —
 * הכפתור הצף של מחשבון הצבע, שני כפתורי הכרזה, והבקשה שמגיעה ב-state
 * של הניווט ממסך ה-404 — ועכשיו יש מקום אחד שקובע את הצורה.
 *
 * מקטע שאינו בעמוד הנוכחי פשוט לא גורם לכלום: זו הסיבה לבדיקה, ולא
 * תקלה שצריך לדווח עליה.
 */

/** גולל אל המקטע המבוקש, אם הוא קיים בעמוד. */
export default function scrollToSection(selector) {
  const el = document.querySelector(selector);
  if (el) el.scrollIntoView({ behavior: 'smooth', block: 'start' });
}
