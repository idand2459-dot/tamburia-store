/** הגוון שברירת המחדל של בורר הגוון תפתח עליו כשאין גוון. */
export const FALLBACK_HEX = '#888888';

/**
 * מנרמל צבע לצורה { name, hex }.
 *
 * מקבל גם מחרוזת, כי תשובה שנשמרה ב-cache של הדפדפן מלפני המיגרציה
 * עדיין מחזיקה שמות בלבד, ואין סיבה שהטופס ייפול עליה.
 */
function asColor(value) {
  if (typeof value === 'string') return { name: value, hex: '' };
  return { name: value?.name ?? '', hex: value?.hex ?? '' };
}

/** מנרמל רשימת צבעים. מחזיר מערך ריק לכל דבר שאינו רשימה. */
export function asColors(value) {
  return Array.isArray(value) ? value.map(asColor) : [];
}
